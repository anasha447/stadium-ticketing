"""Turns the two logo images into small black-and-white bitmaps for the seat mosaic.

Run from frontend/stadium-site:

    python scripts/make-marks.py

It reads the images from .claude/skills/photos/ (kept out of the repo) and
writes lib/stadium/mark-bitmaps.ts. Each bitmap is a list of text rows where
"#" is ink (a yellow seat) and "." is empty (the seat keeps its own colour).
Run it again only if the source images change.
"""

from pathlib import Path

from PIL import Image

PHOTOS = Path(__file__).resolve().parents[3] / ".claude" / "skills" / "photos"
OUT = Path(__file__).resolve().parents[1] / "lib" / "stadium" / "mark-bitmaps.ts"

# name in the output, source file, width of the bitmap in cells
MARKS = [
    ("CREST", "barcelona symbol.jpeg", 112),
    ("SPOTIFY", "sptify symbol.jpeg", 72),
]

INK_BELOW = 128  # darker than this counts as ink


def bitmap(path: Path, width: int) -> list[str]:
    grey = Image.open(path).convert("L")
    ink = grey.point(lambda value: 255 if value < INK_BELOW else 0)
    # Crop to the mark itself, then shrink. Averaging while shrinking and
    # thresholding again keeps thin lines from vanishing.
    cropped = grey.crop(ink.getbbox())
    height = round(width * cropped.height / cropped.width)
    small = cropped.resize((width, height), Image.LANCZOS)
    return [
        "".join("#" if small.getpixel((x, y)) < INK_BELOW + 30 else "." for x in range(width))
        for y in range(height)
    ]


def main() -> None:
    lines = [
        "// Generated by scripts/make-marks.py from the logo images. Do not edit by hand.",
        '// "#" is a yellow seat, "." leaves the seat its own colour. Top row first.',
        "",
    ]
    for name, filename, width in MARKS:
        rows = bitmap(PHOTOS / filename, width)
        lines.append(f"export const {name}: string[] = [")
        lines.extend(f'  "{row}",' for row in rows)
        lines.append("];")
        lines.append("")
        print(f"{name}: {width} x {len(rows)}")
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
